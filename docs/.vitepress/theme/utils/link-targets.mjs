export function headingAnchor(section = "") {
  let slug = section
    .replace(/^#{1,6}\s+/, "")
    .trim()
    .toLowerCase()
    .normalize("NFKC")
    .replace(/[.\s/]+/g, "-")
    .replace(/[^\p{Letter}\p{Number}\p{Mark}_-]/gu, "")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");
  if (/^\d/.test(slug)) slug = `_${slug}`;
  return slug ? `#${slug}` : "";
}

